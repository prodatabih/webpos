import type { Item, ItemType, NormativeMode } from '../types/domain';

export const makeCatalogItem = (
  idNum: number,
  sku: string,
  primaryBarcode: string,
  name: string,
  shortName: string,
  categoryName: string,
  uom: 'kom' | 'kg' | 'l' | 'pak',
  netContentQty: string,
  netContentUom: string,
  countryOfOrigin: string,
  isWeighable = false,
  itemType: ItemType = 'GOODS',
  normativeMode: NormativeMode = 'NONE',
): Item => ({
  id: `item-${idNum}`,
  companyId: 'comp-1',
  sku,
  primaryBarcode,
  name,
  shortName,
  itemType,
  normativeMode,
  uom,
  netContentQty,
  netContentUom,
  vatRateId: 'vat-e17',
  categoryName,
  countryOfOrigin,
  isWeighable,
  isActive: true,
});
